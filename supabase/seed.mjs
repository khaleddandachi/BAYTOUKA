// ============================================================================
// BAYTOUKA (بيتك) — Supabase Seed Script (products.json -> Families & Variants)
// Usage: node supabase/seed.mjs
// Generates supabase/seed-products.sql and optionally seeds a live Supabase URL.
// ============================================================================

import fs from 'node:fs';
import path from 'node:path';
import { extractBaseNameAndVariantLabel } from '../js/families.js';
import { normalizeArabic, CATEGORY_META, DEFAULT_STORE_SETTINGS } from '../js/utils.js';

const rootDir = process.cwd();
const rawJson = fs.readFileSync(path.join(rootDir, 'products.json'), 'utf8').replace(/^\uFEFF/, '');
const products = JSON.parse(rawJson);

function sqlStr(val) {
  if (val === null || val === undefined) return 'NULL';
  return `'${String(val).replace(/'/g, "''")}'`;
}

const lines = [
  '-- Auto-generated by supabase/seed.mjs from products.json (645 products normalized into families)',
  'begin;',
  `update public.settings set data = ${sqlStr(JSON.stringify(DEFAULT_STORE_SETTINGS))}::jsonb, updated_at = now() where id = 1;`
];

CATEGORY_META.forEach((cat, idx) => {
  lines.push(
    `insert into public.categories (id, slug, short_ar, subtitle_ar, icon, art_icon, art_theme, sort_order, active) values (${sqlStr(cat.id)}, ${sqlStr(cat.slug)}, ${sqlStr(cat.shortAr)}, ${sqlStr(cat.subtitleAr)}, ${sqlStr(cat.icon)}, ${sqlStr(cat.artIcon)}, ${sqlStr(cat.artTheme)}, ${idx + 1}, true) on conflict (id) do update set slug = excluded.slug, short_ar = excluded.short_ar, subtitle_ar = excluded.subtitle_ar, art_icon = excluded.art_icon, art_theme = excluded.art_theme;`
  );
});

products.forEach((p, idx) => {
  const id = Number(p.id) || idx + 1;
  const sku = String(p.sku || `SKU-${id}`).trim();
  const box = String(p.box || '—').trim();
  const nameAr = String(p.nameAr || `منتج ${sku}`).trim();
  const descAr = String(p.descAr || '').trim();
  const category = String(p.category || 'أطقم الطناجر والمقالي').trim();
  const specs = String(p.specs || 'Standard').trim();
  const wholesale = Number(parseFloat(p.wholesalePrice ?? 5).toFixed(2));
  const retail = Number(parseFloat(p.retailPrice ?? 8).toFixed(2));
  const cost = Number((wholesale * 0.82).toFixed(2));
  const badge = String(p.badge || '').trim();
  const featured = Boolean(badge);

  const { baseNameAr, variantSuffix } = extractBaseNameAndVariantLabel(nameAr, sku, specs);
  const familyKey = `${normalizeArabic(baseNameAr)}__${normalizeArabic(category)}`;

  lines.push(
    `insert into public.products (id, family_key, sku, box, name_ar, base_name_ar, variant_suffix, desc_ar, category, specs, wholesale_price, retail_price, cost_price, badge, featured, active, image_url, sort_order) values (${id}, ${sqlStr(familyKey)}, ${sqlStr(sku)}, ${sqlStr(box)}, ${sqlStr(nameAr)}, ${sqlStr(baseNameAr)}, ${sqlStr(variantSuffix)}, ${sqlStr(descAr)}, ${sqlStr(category)}, ${sqlStr(specs)}, ${wholesale}, ${retail}, ${cost}, ${sqlStr(badge)}, ${featured}, true, NULL, ${idx + 1}) on conflict (id) do update set family_key = excluded.family_key, base_name_ar = excluded.base_name_ar, variant_suffix = excluded.variant_suffix, wholesale_price = excluded.wholesale_price, retail_price = excluded.retail_price, image_url = NULL;`
  );
});

lines.push('commit;');

const outSqlPath = path.join(rootDir, 'supabase', 'seed-products.sql');
fs.writeFileSync(outSqlPath, lines.join('\n') + '\n', 'utf8');
console.log(`[SEED] Generated ${outSqlPath} with ${products.length} rows.`);

