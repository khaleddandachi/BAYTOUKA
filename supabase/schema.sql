create extension if not exists "pgcrypto";

-- 1. ADMINS TABLE (Maps Supabase Auth users to store admin privileges)
create table if not exists public.admins (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  role text not null default 'owner',
  created_at timestamptz not null default now()
);

-- Helper function to check if the current JWT user is an authorized store admin
create or replace function public.is_store_admin()
returns boolean
language sql
security definer
stable
as $$
  select exists (
    select 1 from public.admins where id = auth.uid()
  );
$$;

-- 2. SETTINGS TABLE (Single-row JSONB store configuration for white-label resale)
create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

insert into public.settings (id, data)
values (1, '{}'::jsonb)
on conflict (id) do nothing;

-- 3. CATEGORIES TABLE
create table if not exists public.categories (
  id text primary key,
  slug text unique not null,
  short_ar text not null,
  subtitle_ar text not null default '',
  icon text not null default 'box',
  art_icon text not null default 'pot-royal-set',
  art_theme text not null default 'saffron',
  sort_order int not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

-- 4. PRODUCTS TABLE (Supports Product Families + Variants + Optional Custom Image)
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  family_key text not null,
  sku text not null,
  box text not null default '—',
  name_ar text not null,
  base_name_ar text not null,
  variant_suffix text not null default '',
  desc_ar text not null default '',
  category text not null,
  specs text not null default 'Standard',
  wholesale_price numeric(10,2) not null check (wholesale_price >= 0),
  retail_price numeric(10,2) not null check (retail_price >= 0),
  cost_price numeric(10,2) default null,
  stock int default null,
  badge text not null default '',
  featured boolean not null default false,
  active boolean not null default true,
  image_url text default null,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_products_family_key on public.products(family_key);
create index if not exists idx_products_category on public.products(category);
create index if not exists idx_products_sku on public.products(sku);
create index if not exists idx_products_active on public.products(active);

-- 5. BRIDAL & CURATED PACKAGES TABLE
create table if not exists public.packages (
  id text primary key,
  name_ar text not null,
  tier_code text not null default 'classic',
  subtitle_ar text not null default '',
  badge_ar text not null default 'باقة متكاملة',
  discount_pct numeric(5,2) not null default 8.00 check (discount_pct >= 0 and discount_pct <= 60),
  items jsonb not null default '[]'::jsonb,
  sort_order int not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

-- 6. ORDERS TABLE (Zero demo rows; populated strictly on customer WhatsApp checkout)
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text unique not null,
  customer_name text not null check (char_length(trim(customer_name)) >= 2),
  customer_phone text not null check (char_length(trim(customer_phone)) >= 6),
  region_id text not null,
  region_name_ar text not null,
  address text not null check (char_length(trim(address)) >= 3),
  notes text default '',
  pricing_mode text not null default 'retail' check (pricing_mode in ('retail', 'wholesale')),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  delivery_fee numeric(10,2) not null default 0 check (delivery_fee >= 0),
  discount_amount numeric(10,2) not null default 0 check (discount_amount >= 0),
  grand_total numeric(10,2) not null check (grand_total >= 0),
  wholesale_cost_total numeric(10,2) not null default 0,
  net_profit numeric(10,2) not null default 0,
  status text not null default 'new' check (status in ('new', 'confirmed', 'delivered', 'cancelled')),
  client_fingerprint text default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_orders_created_at on public.orders(created_at desc);
create index if not exists idx_orders_status on public.orders(status);
create index if not exists idx_orders_phone on public.orders(customer_phone);

-- 7. ORDER ITEMS TABLE
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint default null,
  sku text not null,
  box text default '—',
  name_ar text not null,
  qty int not null check (qty > 0 and qty <= 500),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  wholesale_cost numeric(10,2) not null default 0,
  line_total numeric(10,2) not null check (line_total >= 0)
);

create index if not exists idx_order_items_order_id on public.order_items(order_id);

-- ============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ============================================================================
alter table public.admins enable row level security;
alter table public.settings enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.packages enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Admins table: only authenticated admin can view/manage
create policy "Admins can view admins" on public.admins
  for select using (auth.uid() = id or public.is_store_admin());

-- Settings, Categories, Products, Packages: Public SELECT, Admin-only write
create policy "Public read settings" on public.settings for select using (true);
create policy "Admin write settings" on public.settings for all using (public.is_store_admin()) with check (public.is_store_admin());

create policy "Public read categories" on public.categories for select using (true);
create policy "Admin write categories" on public.categories for all using (public.is_store_admin()) with check (public.is_store_admin());

create policy "Public read active products" on public.products for select using (active = true or public.is_store_admin());
create policy "Admin write products" on public.products for all using (public.is_store_admin()) with check (public.is_store_admin());

create policy "Public read packages" on public.packages for select using (true);
create policy "Admin write packages" on public.packages for all using (public.is_store_admin()) with check (public.is_store_admin());

-- Orders & Order Items: Anonymous users can NEVER SELECT/UPDATE/DELETE; only Admin can!
create policy "Admin full access orders" on public.orders
  for all using (public.is_store_admin()) with check (public.is_store_admin());

create policy "Admin full access order_items" on public.order_items
  for all using (public.is_store_admin()) with check (public.is_store_admin());

-- ============================================================================
-- SERVER-SIDE VALIDATED ORDER CREATION RPC (Prevents Price Spoofing & Spam)
-- Anonymous customers call `supabase.rpc('submit_customer_order', payload)`
-- ============================================================================
create or replace function public.submit_customer_order(
  p_customer_name text,
  p_customer_phone text,
  p_region_id text,
  p_region_name_ar text,
  p_address text,
  p_notes text,
  p_pricing_mode text,
  p_delivery_fee numeric,
  p_client_fingerprint text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_recent_count int;
  v_order_id uuid;
  v_order_num text;
  v_subtotal numeric(10,2) := 0;
  v_cost_total numeric(10,2) := 0;
  v_grand_total numeric(10,2) := 0;
  v_net_profit numeric(10,2) := 0;
  v_safe_delivery numeric(10,2) := greatest(0, coalesce(p_delivery_fee, 3.00));
  v_item jsonb;
  v_prod record;
  v_qty int;
  v_unit_price numeric(10,2);
  v_unit_cost numeric(10,2);
  v_line_total numeric(10,2);
begin
  if char_length(trim(coalesce(p_customer_name, ''))) < 2 then
    raise exception 'Invalid customer name';
  end if;
  if char_length(trim(coalesce(p_customer_phone, ''))) < 6 then
    raise exception 'Invalid customer phone';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Order must contain at least one item';
  end if;

  -- Rate limit: max 6 orders per 10 minutes from same phone or fingerprint
  select count(*) into v_recent_count
  from public.orders
  where created_at > now() - interval '10 minutes'
    and (
      customer_phone = trim(p_customer_phone)
      or (char_length(coalesce(p_client_fingerprint, '')) > 6 and client_fingerprint = p_client_fingerprint)
    );

  if v_recent_count >= 6 then
    raise exception 'Rate limit exceeded. Please wait a few minutes before submitting another order.';
  end if;

  v_order_num := 'BYT-' || to_char(now(), 'YYYYMMDD') || '-' || upper(substr(md5(random()::text), 1, 4));

  -- First pass: compute server-verified totals from public.products
  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_qty := greatest(1, least(500, coalesce((v_item->>'qty')::int, 1)));
    select * into v_prod
    from public.products
    where sku = (v_item->>'sku') or id = coalesce((v_item->>'productId')::bigint, -1)
    limit 1;

    if found then
      if p_pricing_mode = 'wholesale' then
        v_unit_price := v_prod.wholesale_price;
      else
        v_unit_price := v_prod.retail_price;
      end if;
      v_unit_cost := coalesce(v_prod.cost_price, round(v_prod.wholesale_price * 0.82, 2));
    else
      v_unit_price := greatest(0.25, coalesce((v_item->>'unitPrice')::numeric, 5.00));
      v_unit_cost := greatest(0.20, coalesce((v_item->>'wholesaleCost')::numeric, v_unit_price * 0.75));
    end if;

    v_line_total := round(v_unit_price * v_qty, 2);
    v_subtotal := v_subtotal + v_line_total;
    v_cost_total := v_cost_total + round(v_unit_cost * v_qty, 2);
  end loop;

  v_grand_total := v_subtotal + v_safe_delivery;
  v_net_profit := v_subtotal - v_cost_total;

  insert into public.orders (
    order_number, customer_name, customer_phone, region_id, region_name_ar,
    address, notes, pricing_mode, subtotal, delivery_fee, grand_total,
    wholesale_cost_total, net_profit, status, client_fingerprint
  ) values (
    v_order_num, trim(p_customer_name), trim(p_customer_phone), coalesce(p_region_id, 'tripoli'),
    coalesce(p_region_name_ar, 'طرابلس والشمال'), trim(p_address), coalesce(p_notes, ''),
    case when p_pricing_mode = 'wholesale' then 'wholesale' else 'retail' end,
    v_subtotal, v_safe_delivery, v_grand_total, v_cost_total, v_net_profit,
    'new', coalesce(p_client_fingerprint, '')
  ) returning id into v_order_id;

  -- Second pass: insert order items
  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_qty := greatest(1, least(500, coalesce((v_item->>'qty')::int, 1)));
    select * into v_prod
    from public.products
    where sku = (v_item->>'sku') or id = coalesce((v_item->>'productId')::bigint, -1)
    limit 1;

    if found then
      v_unit_price := case when p_pricing_mode = 'wholesale' then v_prod.wholesale_price else v_prod.retail_price end;
      v_unit_cost := coalesce(v_prod.cost_price, round(v_prod.wholesale_price * 0.82, 2));
    else
      v_unit_price := greatest(0.25, coalesce((v_item->>'unitPrice')::numeric, 5.00));
      v_unit_cost := greatest(0.20, coalesce((v_item->>'wholesaleCost')::numeric, v_unit_price * 0.75));
    end if;

    insert into public.order_items (
      order_id, product_id, sku, box, name_ar, qty, unit_price, wholesale_cost, line_total
    ) values (
      v_order_id,
      coalesce(v_prod.id, (v_item->>'productId')::bigint),
      coalesce(v_prod.sku, v_item->>'sku', 'SKU'),
      coalesce(v_prod.box, v_item->>'box', '—'),
      coalesce(v_prod.name_ar, v_item->>'nameAr', 'صنف'),
      v_qty,
      v_unit_price,
      v_unit_cost,
      round(v_unit_price * v_qty, 2)
    );
  end loop;

  return jsonb_build_object(
    'orderId', v_order_id,
    'orderNumber', v_order_num,
    'subtotal', v_subtotal,
    'deliveryFee', v_safe_delivery,
    'grandTotal', v_grand_total,
    'status', 'new',
    'createdAt', now()
  );
end;
$$;

grant execute on function public.submit_customer_order(text, text, text, text, text, text, text, numeric, text, jsonb) to anon, authenticated;

